CREATE TEMP TABLE _ribera_property (id UUID PRIMARY KEY) ON COMMIT DROP;
LOCK TABLE public.copropiedades IN SHARE ROW EXCLUSIVE MODE;
LOCK TABLE public.unidades IN SHARE ROW EXCLUSIVE MODE;
LOCK TABLE public.asambleas IN SHARE ROW EXCLUSIVE MODE;

DO $register_property$
DECLARE
  requested_nit TEXT := NULLIF(trim(current_setting('app.ribera_nit', true)), '');
  matches BIGINT;
  registered_nit TEXT;
BEGIN
  IF requested_nit IS NULL OR regexp_replace(requested_nit, '[^0-9]', '', 'g') <> '9020699486' THEN
    RAISE EXCEPTION 'Carga abortada: el NIT debe coincidir con el RUT de Ribera Campestre P.H.';
  END IF;
  SELECT count(*) INTO matches
    FROM public.copropiedades
    WHERE nombre ILIKE '%Ribera Campestre%';
  IF matches > 1 THEN
    RAISE EXCEPTION 'Carga abortada: hay % copropiedades cuyo nombre coincide con Ribera Campestre.', matches;
  ELSIF matches = 1 THEN
    SELECT nit INTO registered_nit
      FROM public.copropiedades
      WHERE nombre ILIKE '%Ribera Campestre%';
    IF regexp_replace(registered_nit, '[^0-9]', '', 'g') <> regexp_replace(requested_nit, '[^0-9]', '', 'g') THEN
      RAISE EXCEPTION 'Carga abortada: Ribera Campestre ya existe con otro NIT.';
    END IF;
  ELSE
    INSERT INTO public.copropiedades(nombre, nit)
    VALUES ('RIBERA CAMPESTRE PROPIEDAD HORIZONTAL', requested_nit);
  END IF;
END;
$register_property$;

INSERT INTO _ribera_property (id)
SELECT id FROM public.copropiedades
WHERE nombre ILIKE '%Ribera Campestre%'
  AND regexp_replace(nit, '[^0-9]', '', 'g') = regexp_replace(current_setting('app.ribera_nit', true), '[^0-9]', '', 'g');

SELECT set_config('app.id_copropiedad', id::text, true)
FROM _ribera_property;

DO $preflight$
DECLARE
  stage_count BIGINT;
  property_count BIGINT;
  existing_count BIGINT;
  source_total NUMERIC(12,6);
  normalized_total NUMERIC(12,6);
BEGIN
  SELECT count(*), sum(coeficiente_fuente), sum(coeficiente_normalizado)
    INTO stage_count, source_total, normalized_total
    FROM _ribera_stage;
  SELECT count(*) INTO property_count FROM _ribera_property;
  IF stage_count <> 628 THEN
    RAISE EXCEPTION 'Carga abortada: se esperaban 628 unidades, hay %', stage_count;
  END IF;
  IF source_total <> 99.995200 THEN
    RAISE EXCEPTION 'Carga abortada: suma fuente inesperada: %', source_total;
  END IF;
  IF normalized_total <> 100.000000 THEN
    RAISE EXCEPTION 'Carga abortada: coeficientes normalizados suman %', normalized_total;
  END IF;
  IF property_count <> 1 THEN
    RAISE EXCEPTION 'Carga abortada: se esperaba una copropiedad existente Ribera Campestre, se encontraron %', property_count;
  END IF;
  SELECT count(*) INTO existing_count
    FROM public.unidades u JOIN _ribera_property p ON p.id = u.id_copropiedad;
  IF existing_count <> 0 THEN
    RAISE EXCEPTION 'Carga abortada: la copropiedad ya tiene % unidades; no se modifica ni duplica el padrón', existing_count;
  END IF;
END;
$preflight$;

INSERT INTO public.unidades (id_copropiedad, numero_inmueble, coeficiente)
SELECT p.id, s.numero_inmueble, s.coeficiente_normalizado
FROM _ribera_stage s
CROSS JOIN _ribera_property p
ORDER BY s.orden;

INSERT INTO public.asambleas (id, id_copropiedad, fecha, estado)
SELECT '00000000-0000-4000-8000-000000000101'::uuid, p.id, now(), 'activa'
FROM _ribera_property p;

DO $postflight$
DECLARE
  inserted_count BIGINT;
  database_total NUMERIC(12,6);
  assembly_count BIGINT;
BEGIN
  SELECT count(*), sum(u.coeficiente)
    INTO inserted_count, database_total
    FROM public.unidades u JOIN _ribera_property p ON p.id = u.id_copropiedad;
  IF inserted_count <> 628 OR database_total <> 100.000000 THEN
    RAISE EXCEPTION 'Verificación final falló: unidades=%, suma=%', inserted_count, database_total;
  END IF;
  SELECT count(*) INTO assembly_count
    FROM public.asambleas a JOIN _ribera_property p ON p.id = a.id_copropiedad
    WHERE a.id = '00000000-0000-4000-8000-000000000101'::uuid AND a.estado = 'activa';
  IF assembly_count <> 1 THEN
    RAISE EXCEPTION 'Verificación final falló: no quedó exactamente una asamblea principal activa.';
  END IF;
END;
$postflight$;

COMMIT;
